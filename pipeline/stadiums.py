# 正式名称 -> jcd
NAME_TO_JCD = {v: k for k, v in STADIUMS.items()}


def resolve(text: str):
    """レース場名・かな・場コードから jcd を返す。解決できなければ None."""
    t = text.strip().replace("　", "").replace(" ", "")
    t = t.replace("ボートレース", "").replace("競艇", "").replace("場", "")

    if t.isdigit():
        n = int(t)
        return n if n in STADIUMS else None
    if t in NAME_TO_JCD:
        return NAME_TO_JCD[t]
    if t in ALIASES:
        return ALIASES[t]
    # 部分一致（「大村」で「大村」など既に上でヒットするが、揺れ対策）
    for name, jcd in NAME_TO_JCD.items():
        if name in t or t in name:
            return jcd
    return None


def name(jcd: int) -> str:
    return STADIUMS.get(jcd, f"不明({jcd})")
